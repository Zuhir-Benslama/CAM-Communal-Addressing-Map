    def _push_combos(self) -> None:
        for name in self.dialog._combo_proxies:
            self._push_combo(name)

    def _push_combo(self, name: str) -> None:
        """Push locally stored combo data to QML."""
        proxy = self.dialog._combo_proxies.get(name)
        if not proxy:
            return
        items = [
            {'text': str(v.get('text', '')), 'value': str(v.get('value', ''))}
            for v in proxy._items
        ]
        logger.info(
            '_push_combo %s: %d items, proxy._index=%d', name, len(items), proxy._index
        )
        root = self._qml_root()
        if root:
            root.setComboOptions(name, items)

    def _push_field(self, name: str) -> None:
        proxy = self.dialog._field_proxies.get(name)
        if not proxy:
            return
        root = self._qml_root()
        if root:
            root.setFieldText(name, proxy._text)


