    def _translate_internal_combos(self) -> None:
        loc = self._tr_locale
        layer_selector = self._combo_proxies.get('layer_selector')
        if layer_selector:
            for i, name in enumerate(self.LAYER_INDEX_MAP):
                layer_selector.setItemText(i, get_string(name, loc))
        theme_combo = self._combo_proxies.get('_theme_combo')
        if theme_combo:
            for i in range(theme_combo.count()):
                theme_value = theme_combo.itemData(i)
                theme_combo.setItemText(i, get_string(theme_value, loc))

    # ------------------------------------------------------------------
    # Theme / locale
    # ------------------------------------------------------------------
    def _init_theme_locale(self) -> None:
        settings = QSettings(SETTINGS_ORG, SETTINGS_APP)
        theme_combo = self._combo_proxies.get('_theme_combo')
        if theme_combo:
            theme_combo.addItem(THEME_DARK, THEME_DARK)
            theme_combo.addItem(THEME_LIGHT, THEME_LIGHT)
            saved_theme = settings.value(SETTINGS_KEY_THEME, DEFAULT_THEME)
            theme_map = {'فاتح': THEME_LIGHT, 'داكن': THEME_DARK}
            saved_theme = theme_map.get(saved_theme, saved_theme)
            try:
                idx = theme_combo.findData(saved_theme)
            except (ValueError, TypeError):
                idx = -1
            if idx >= 0:
                theme_combo.setCurrentIndex(idx)
                settings.setValue(SETTINGS_KEY_THEME, saved_theme)
            self._current_theme = theme_combo.currentData()
        locale_combo = self._combo_proxies.get('_locale_combo')
        if locale_combo:
            for code, label in AVAILABLE_LOCALES:
                locale_combo.addItem(label, code)
            saved_locale = settings.value(SETTINGS_KEY_LOCALE, '')
            if saved_locale:
                li = locale_combo.findData(saved_locale)
                if li >= 0:
                    locale_combo.setCurrentIndex(li)

    def _on_theme_changed(self, _index: int) -> None:
        theme_combo = self._combo_proxies.get('_theme_combo')
        if theme_combo:
            self._current_theme = theme_combo.currentData()
        settings = QSettings(SETTINGS_ORG, SETTINGS_APP)
        settings.setValue(SETTINGS_KEY_THEME, self._current_theme)
        self.apply_theme()

    def _on_locale_changed(self, _idx: int) -> None:
        locale_combo = self._combo_proxies.get('_locale_combo')
        if not locale_combo:
            return
        code = locale_combo.currentData()
        if not code:
            return
        settings = QSettings(SETTINGS_ORG, SETTINGS_APP)
        settings.setValue(SETTINGS_KEY_LOCALE, code)
        self._tr_locale = code
        clear_i18n_cache()
        apply_widget_texts(self, code)
        self._translate_internal_combos()
        fill_wilayas_list(self._combo_proxies.get('wilaya_list'))
        fill_road_type(self._combo_proxies.get('type_road'))
        fill_zone_type(self._combo_proxies.get('zone_type'))
        fill_subdivision_type(self._combo_proxies.get('subd_type'))
        fill_mounting_status(self._combo_proxies.get('mount_status'))
        fill_numbering_state(self._combo_proxies.get('num_state'))
        fill_road_reference(self._combo_proxies.get('road_ref'))
        fill_panel_reference(self._combo_proxies.get('panel_ref'))
        fill_paper(self._combo_proxies.get('paper'))
        fill_org_category(self._combo_proxies.get('org_cat'))
        fill_activity_category(self._combo_proxies.get('activity_cat'))
        if code == 'ar':
            QApplication.setLayoutDirection(Qt.LayoutDirection.RightToLeft)
        else:
            QApplication.setLayoutDirection(Qt.LayoutDirection.LeftToRight)
        try:
            root = self._quick_widget.rootObject()
            if root:
                root.updateLayoutDirection(code == 'ar')
        except Exception:
            pass

    def apply_theme(self) -> None:
        theme = self._current_theme
        qss = get_theme_qss(theme)
        self.setStyleSheet(qss)
        is_dark = theme == 'dark'
        try:
            root = self._quick_widget.rootObject()
            if root:
                root.updateTheme(is_dark)
        except Exception:
            pass
