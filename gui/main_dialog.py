    def _pull_fields(self) -> None:
        root = self._qml_root()
        if not root:
            return
        for name, proxy in self.dialog._field_proxies.items():
            qml_text = str(root.getFieldText(name))
            proxy._text = qml_text

    @pyqtSlot(str)
    def onPageSubmit(self, pageName: str) -> None:
        d = self.dialog
        self._pull_fields()
        dispatch = {
            'login': d.login_user,
            'add_usr': d.submit_add_usr,
            'restore_db': d.restore_database,
            'zone': d.add_zone,
            'road': d.add_road,
            'org': d.add_organization,
            'city': d.add_city,
            'num': d.add_numbering,
            'pan': d.add_panel,
            'toggle_settings': d._toggle_settings,
            'draw': d.start_drawing,
            'select': d.start_selecting,
            'edit': d.start_editing,
            'measure': d.activate_measure,
            'save_action': d._on_save_action,
            'save_new_type': d._save_new_type,
            'list_roads': d.list_road_entries,
            'list_orgs': d.list_organizations,
            'list_subds': d.list_subdivisions,
            'list_nums': d.list_numberings,
            'list_panels': d.list_panel_signs,
        }
        handler = dispatch.get(pageName)
        if handler:
            handler()

    @pyqtSlot(str, int, str)
    def onComboChanged(self, objectName: str, index: int, currentData: str) -> None:
        d = self.dialog
        if objectName == 'wilaya_list':
            d.on_select_wilaya(index)
        elif objectName == 'org_cat':
            d.on_select_org_cat(index)
        elif objectName == 'activity_cat':
            d.on_select_activity_cat(index)
        elif objectName == 'layer_selector':
            d._on_layer_changed(index)
        elif objectName == 'feature_combo':
            d._on_feature_changed(index)
        elif objectName == 'map_options':
            proxy = d._combo_proxies.get('map_options')
            if proxy:
                proxy.setCurrentIndex(index)
                logger.info(
                    'onComboChanged map_options: index=%d, text=%s, data=%s',
                    index,
                    proxy.currentText(),
                    proxy.currentData(),
                )
        elif objectName == '_action_combo':
            d._on_action_changed(index)
        elif objectName == 'menu':
            d.on_opt_selected(index)
        elif objectName == '_theme_combo':
            d._on_theme_changed(index)
        elif objectName == '_locale_combo':
            d._on_locale_changed(index)

    @pyqtSlot(str, str)
    def onSelectRef(self, objectName: str, layerName: str) -> None:
        d = self.dialog
        if objectName == 'road_ref':
            d.select_ref_handler()
