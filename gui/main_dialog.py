    def _on_action_changed(self, _index: int) -> None:
        action_proxy = self._combo_proxies.get('_action_combo')
        action = action_proxy.currentData() if action_proxy else None
        paper_proxy = self._combo_proxies.get('paper')
        is_map = action in ('panels_map', 'num_map')
        if paper_proxy:
            paper_proxy.setVisible(is_map)
        if action == 'panels_map':
            self.panel_chart()
        elif action == 'num_map':
            self.numbering_chart()

    def _on_save_action(self) -> None:
        directory = QFileDialog.getExistingDirectory(
            self,
            self._tr('Choose output directory'),
            self._output_dir,
        )
        if not directory:
            return
        self._output_dir = directory
        action_proxy = self._combo_proxies.get('_action_combo')
        action = action_proxy.currentData() if action_proxy else None
        if action == 'report':
            self.generate_report()
        elif action == 'order':
            self.purchase_order()
        elif action == 'panels_map':
            self.panel_chart()
            self.export_to_image()
        elif action == 'num_map':
            self.numbering_chart()
            self.export_to_image()
        elif action == 'backup':
            self.backup()

    # ------------------------------------------------------------------
    # Feature / type management
    # ------------------------------------------------------------------
    def _on_feature_changed(self, index: int) -> None:
        feature_combo = self._combo_proxies.get('feature_combo')
        if not feature_combo:
            return
        main_type = feature_combo.itemData(index)
        if not isinstance(main_type, str):
            return
        is_activity = main_type == _ACTIVITY_KEY
        label_subtype = self._field_proxies.get('label_subtype')
        new_type = self._field_proxies.get('new_type')
        if label_subtype:
            label_subtype.setVisible(is_activity)
        if new_type:
            new_type.setVisible(is_activity)
        subtype_combo = self._combo_proxies.get('subtype_combo')
        if subtype_combo:
            fill_subtype_combo(subtype_combo, main_type)

    def _save_new_type(self) -> None:
        feature_combo = self._combo_proxies.get('feature_combo')
        if not feature_combo:
            return
        index = feature_combo.currentIndex()
        main_type = feature_combo.itemData(index)
        new_type_proxy = self._field_proxies.get('new_type')
        type_name = new_type_proxy.text().strip() if new_type_proxy else ''
        subtype_combo = self._combo_proxies.get('subtype_combo')
        if not type_name and subtype_combo:
            type_name = subtype_combo.currentText().strip()
        category = (
            subtype_combo.currentData()
            if subtype_combo and main_type == _ACTIVITY_KEY
            else ''
        )
        if save_new_type(main_type, type_name, category):
            if new_type_proxy:
                new_type_proxy.clear()
            if subtype_combo:
                fill_subtype_combo(subtype_combo, main_type)
                clear_i18n_cache()
                count = subtype_combo.count()
                if count > 0:
                    subtype_combo.setCurrentIndex(count - 1)

