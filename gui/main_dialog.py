    def _align_main_margins(self) -> None:
        """Match toolbar and footer horizontal margins to tab content."""
        ref = self.layer_selector
        if ref is None:
            return
        tab_left = ref.mapTo(self, ref.rect().topLeft()).x()
        tab_right = ref.mapTo(self, ref.rect().topRight()).x()
        f8 = self.frame_8
        if f8 is not None:
            f8_left = f8.mapTo(self, f8.rect().topLeft()).x()
            f8_right = f8.mapTo(self, f8.rect().topRight()).x()
            fm = f8.layout().contentsMargins()
            f8.layout().setContentsMargins(
                tab_left - f8_left, fm.top(),
                f8_right - tab_right, fm.bottom(),
            )
        f9 = self.frame_9
        if f9 is not None:
            f9_left = f9.mapTo(self, f9.contentsRect().topLeft()).x()
            f9_right = f9.mapTo(self, f9.contentsRect().topRight()).x()
            f9.layout().setContentsMargins(
                tab_left - f9_left, 2,
                f9_right - tab_right, 2,
            )

    def _set_button_roles(self) -> None:
        """Assign semantic role properties to all push buttons."""
        primary_buttons = {
            'sign_in_user',
            'submit_usr',
            'submit_zone',
            'submit_road',
            'submit_org',
            'submit_subd',
            'submit_num',
            'submit_pan',
            'restore_db',
            'add_type_btn',
            '_save_action',
        }
        danger_buttons = {'abort_uc'}
        tool_prefixes = ('draw_', 'select_', 'edit_')
        expanding_buttons = {'mesure_dist'}

        for button in self.findChildren(QPushButton):
            name = button.objectName()
            if name in primary_buttons:
                button.setProperty('role', 'primary')
            elif name in danger_buttons:
                button.setProperty('role', 'danger')
            elif any(name.startswith(prefix) for prefix in tool_prefixes):
                button.setProperty('role', 'tool')
                button.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Fixed)
            else:
                button.setProperty('role', 'ghost')

            button.setMinimumHeight(max(button.minimumHeight(), 34))
            if name in primary_buttons or name == 'sign_in_user':
                button.setMinimumWidth(180)
                button.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Fixed)
            elif name in expanding_buttons:
                button.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Fixed)
            else:
                button.setMaximumWidth(16777215)
            button.setIconSize(QSize(16, 16))
        self._expand_primary_buttons()

    @staticmethod
    def _layout_has_primary(
        layout: QHBoxLayout, primary_names: set[str],
    ) -> bool:
        """Check whether *layout* contains any button with a primary name."""
        for i in range(layout.count()):
            item = layout.itemAt(i)
            if item:
                widget = item.widget()
                if widget and widget.objectName() in primary_names:
                    return True
        return False

    @staticmethod
    def _set_primary_stretch(
        layout: QHBoxLayout, primary_names: set[str],
    ) -> None:
        """Set Expanding size policy on primary buttons within *layout*."""
        for i in range(layout.count()):
            item = layout.itemAt(i)
            if item:
                widget = item.widget()
                if widget and widget.objectName() in primary_names:
                    widget.setSizePolicy(
                        QSizePolicy.Expanding, QSizePolicy.Fixed,
                    )

    def _expand_primary_buttons(self) -> None:
        """Make primary buttons expand to fill available width."""
        primary_names = {
            'sign_in_user', 'submit_usr', 'submit_zone', 'submit_road',
            'submit_org', 'submit_subd', 'submit_num', 'submit_pan',
        }
        for layout in self.findChildren(QHBoxLayout):
            if not self._layout_has_primary(layout, primary_names):
                continue
            self._set_primary_stretch(layout, primary_names)

    def apply_theme(self) -> None:
        """Apply the current theme stylesheet to the dialog."""
        theme = self._current_theme
        qss = get_theme_qss(theme)
        self.setStyleSheet(qss)
