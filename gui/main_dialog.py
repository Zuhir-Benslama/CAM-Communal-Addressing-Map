    def _on_action_changed(self, _index: int) -> None:
        action = self._combo_action.currentData()
        is_map = action in ('panels_map', 'num_map')
        self._combo_paper.setVisible(is_map)
        if action == 'panels_map':
            self.panel_chart()
        elif action == 'num_map':
            self.numbering_chart()

    def _on_save_action(self) -> None:
        directory = QFileDialog.getExistingDirectory(
            self,
            self._tr('Choose output directory'),
            self._output_dir,
        )
        if not directory:
            return
        self._output_dir = directory
        action = self._combo_action.currentData()
        if action == 'report':
            self.generate_report()
        elif action == 'order':
            self.purchase_order()
        elif action == 'panels_map':
            self.panel_chart()
            self.export_to_image()
        elif action == 'num_map':
            self.numbering_chart()
            self.export_to_image()
        elif action == 'backup':
            self.backup()

