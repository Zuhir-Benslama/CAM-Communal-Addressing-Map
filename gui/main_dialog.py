    def _save_new_type(self) -> None:
        """Save a new type entry to the JSON lookup file."""
        index = self.feature_combo.currentIndex()
        main_type = self.feature_combo.itemData(index)
        type_name = self.new_type.text().strip()
        if not type_name:
            type_name = self.subtype_combo.currentText().strip()
        category = (
            self.subtype_combo.currentData()
            if main_type == _ACTIVITY_KEY else ''
        )
        if save_new_type(main_type, type_name, category):
            self.new_type.clear()
            fill_subtype_combo(self.subtype_combo, main_type)
            clear_i18n_cache()
            count = self.subtype_combo.count()
            if count > 0:
                self.subtype_combo.setCurrentIndex(count - 1)

